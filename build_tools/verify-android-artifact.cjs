// Check the APK that CI actually built; no signing credentials are required.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execFileSync } = require('child_process');
const root = path.resolve(__dirname, '..');
const sdk = process.env.ANDROID_SDK_ROOT || process.env.ANDROID_HOME || (process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'Android', 'Sdk'));
if (!sdk) throw new Error('Android SDK location is unavailable');
const versions = fs.readdirSync(path.join(sdk, 'build-tools')).filter(v => /^\d+(\.\d+)*$/.test(v)).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
const tools = path.join(sdk, 'build-tools', versions.at(-1));
const apk = path.join(root, 'android/app/build/outputs/apk/debug/app-debug.apk');
const run = (command, args) => execFileSync(command, args, { encoding: 'utf8', windowsHide: true });
const badging = run(path.join(tools, process.platform === 'win32' ? 'aapt.exe' : 'aapt'), ['dump', 'badging', apk]);
const match = badging.match(/package: name='([^']+)' versionCode='([^']+)' versionName='([^']+)'/);
if (!match) throw new Error('APK package metadata is missing');
const expected = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const gradle = fs.readFileSync(path.join(root, 'android/app/build.gradle'), 'utf8');
const expectedCode = gradle.match(/versionCode\s+(\d+)/)[1];
const expectedId = 'com.laplacengan.memora' + (process.argv.includes('--qa') ? '.qa' : '');
if (match[1] !== expectedId || match[2] !== expectedCode || match[3] !== expected.version) throw new Error('APK package/version differs from source');
if (!/application-debuggable/.test(badging)) throw new Error('Expected a debug APK');
const java = process.env.JAVA_HOME ? path.join(process.env.JAVA_HOME, 'bin', process.platform === 'win32' ? 'java.exe' : 'java') : 'java';
const signature = run(java, ['-jar', path.join(tools, 'lib/apksigner.jar'), 'verify', '--verbose', '--print-certs', apk]);
if (!/Verified/.test(signature)) throw new Error('APK signature did not verify');
const sha256 = crypto.createHash('sha256').update(fs.readFileSync(apk)).digest('hex');
const metadata = { package: match[1], versionCode: Number(match[2]), versionName: match[3], minSdk: Number(badging.match(/sdkVersion:'(\d+)'/)[1]), targetSdk: Number(badging.match(/targetSdkVersion:'(\d+)'/)[1]), sha256, bytes: fs.statSync(apk).size, signatureVerified: true };
fs.writeFileSync(apk + '.sha256', `${sha256}  ${path.basename(apk)}\n`);
fs.writeFileSync(apk.replace(/\.apk$/, '.metadata.json'), JSON.stringify(metadata, null, 2) + '\n');
console.log(JSON.stringify(metadata, null, 2));
